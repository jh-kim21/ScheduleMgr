-- PM의 잡무 목록(TODO). WBS(산출물)·Backlog(팀 실행 항목)·RAID(위험·이슈) 어디에도 맞지 않는
-- "고객 회의 준비" 같은 일을 적어 두는 곳이다. 다른 표와 연결하지 않는다(사용자 결정).
--
-- completed_at 하나로 완료를 표현한다. done 불리언을 따로 두면 두 값이 어긋날 수 있다 --
-- 완료 여부는 이 값이 있는가이고, 언제 끝냈는지는 값 자체가 말한다.
--
-- assignee_member_id 는 ON DELETE SET NULL 이다(V6의 owner_member_id 와 같은 이유). 구성원이 빠지면
-- 할 일은 남고 담당자 칸만 비워져야 한다. CASCADE 면 기록이 사라진다.
-- 프로젝트가 지워지면 할 일도 함께 사라진다(CASCADE).
CREATE TABLE todo_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    priority VARCHAR(20) NOT NULL,
    assignee_member_id BIGINT,
    due_date DATE,
    memo VARCHAR(2000),
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_todo_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_todo_assignee FOREIGN KEY (assignee_member_id) REFERENCES project_members (id) ON DELETE SET NULL
);

CREATE INDEX idx_todo_project ON todo_items (project_id);
